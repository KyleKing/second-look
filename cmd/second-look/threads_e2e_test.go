// The conversation queue is GraphQL and nothing local, so these run outside a
// checkout, and the read marks they would write are pointed at a temporary
// config directory rather than the real one.
//
// The cassette is built here rather than checked in. A real recording carries
// the private repository names, logins, and pull request titles of whatever is
// open, and this repository is public; building it from conversations.LightArgs
// and HeavyArgs means the calls it answers are the calls the fetcher makes,
// which a hand-written copy of a 60-line GraphQL query would stop being on the
// first edit.
func TestThreads(t *testing.T) {
	t.Parallel()

	s := ghcassette.Replay(t, queueCassette(t))

	res := runCLI(t, s, t.TempDir(), "threads")
	if res.code != 0 {
		t.Fatalf("threads failed: %s%s", res.stdout, res.stderr)
	}

	for _, want := range []string{
		conversations.BucketNew,
		conversations.BucketWaiting,
		conversations.BucketAwaiting,
		// The bot's inline thread is admitted, since it is anchored to code and
		// can be resolved.
		"a.go:12",
		// The pull request title rides along, because a repository and a number
		// are not enough to know what a conversation is about.
		"mine",
	} {
		if !strings.Contains(res.stdout, want) {
			t.Errorf("%q is missing from the queue:\n%s", want, res.stdout)
		}
	}

	// A bot's pull request comment, a review body it wrote, and a comment
	// already thumbs-upped are all dropped, and the queue is worthless if they
	// are not.
	for _, unwanted := range []string{"Coverage report", "generated by a bot", "already handled"} {
		if strings.Contains(res.stdout, unwanted) {
			t.Errorf("%q reached the queue:\n%s", unwanted, res.stdout)
		}
	}

	s.RequireAllPlayed(t)
}

// Printing the queue is not reading it, so a run that emptied the first bucket
// by being run would hide the one thing that bucket is for.
func TestThreadsWritesNoReadMarks(t *testing.T) {
	t.Parallel()

	s := ghcassette.Replay(t, queueCassette(t))
	home := quietHome(t)

	res := runCLIEnv(t, s, t.TempDir(), []string{"HOME=" + home, "XDG_CONFIG_HOME=" + home + "/.config"}, "threads")
	if res.code != 0 {
		t.Fatalf("threads failed: %s%s", res.stdout, res.stderr)
	}

	if found := marks(t, home); found != "" {
		t.Errorf("printing the queue wrote read marks at %s", found)
	}
}

// marks is where read state was written under home, or empty when none was.
func marks(t *testing.T, home string) string {
	t.Helper()

	var found string

	err := filepath.WalkDir(home, func(path string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() && d.Name() == "conversations.toml" {
			found = path
		}

		return nil
	})
	if err != nil {
		t.Fatalf("walking %s: %v", home, err)
	}

	return found
}

// --json is what an agent reads, so the buckets and every field a script needs
// have to survive it.
func TestThreadsJSON(t *testing.T) {
	t.Parallel()

	s := ghcassette.Replay(t, queueCassette(t))

	res := runCLI(t, s, t.TempDir(), "threads", "--json")
	if res.code != 0 {
		t.Fatalf("threads --json failed: %s%s", res.stdout, res.stderr)
	}

	var buckets []struct {
		Name  string                       `json:"name"`
		Items []conversations.Conversation `json:"items"`
	}

	if err := json.Unmarshal([]byte(res.stdout), &buckets); err != nil {
		t.Fatalf("reading the buckets: %v\n%s", err, res.stdout)
	}

	if len(buckets) != 3 {
		t.Fatalf("printed %d buckets, want 3:\n%s", len(buckets), res.stdout)
	}

	var seen int

	for i := range buckets {
		for j := range buckets[i].Items {
			c := &buckets[i].Items[j]
			seen++

			if c.Repository == "" || c.Number == 0 || len(c.Notes) == 0 || !c.Why.Any() {
				t.Errorf("a conversation carries too little to act on: %+v", c)
			}
		}
	}

	if seen == 0 {
		t.Fatal("no conversations were printed, so nothing here is exercised")
	}
}

// queueFixture is the hand-written queue the conversations package tests
// against, which is the only fixture of this shape and the one place its rules
// are written down. The light answer is derived from it, so the pull requests
// the light read finds are the ones the heavy read is asked about.
type queueFixture struct {
	viewer json.RawMessage
	nodes  []fixtureNode
}

// fixtureNode is one pull request of the fixture. Fields keeps everything the
// heavy read answers, and the rest is what the light read answers with.
//
//nolint:tagliatelle // GraphQL answers in camelCase and these names are GitHub's
type fixtureNode struct {
	ID         string `json:"id"`
	Number     int    `json:"number"`
	Repository struct {
		NameWithOwner string `json:"nameWithOwner"`
	} `json:"repository"`
	fields map[string]json.RawMessage
}

func readQueueFixture(t *testing.T) queueFixture {
	t.Helper()

	body, err := os.ReadFile(filepath.Join("..", "..", "internal", "conversations", "testdata", "queue.json"))
	if err != nil {
		t.Fatalf("reading the queue fixture: %v", err)
	}

	var fixture struct {
		Data struct {
			Viewer json.RawMessage   `json:"viewer"`
			Nodes  []json.RawMessage `json:"nodes"`
		} `json:"data"`
	}

	if err := json.Unmarshal(body, &fixture); err != nil {
		t.Fatalf("reading the queue fixture: %v", err)
	}

	q := queueFixture{viewer: fixture.Data.Viewer}

	for _, raw := range fixture.Data.Nodes {
		var n fixtureNode

		if err := json.Unmarshal(raw, &n); err != nil {
			t.Fatalf("reading a pull request of the queue fixture: %v", err)
		}

		if err := json.Unmarshal(raw, &n.fields); err != nil {
			t.Fatalf("reading a pull request of the queue fixture: %v", err)
		}

		q.nodes = append(q.nodes, n)
	}

	return q
}

func (q queueFixture) ids() []string {
	ids := make([]string, 0, len(q.nodes))
	for i := range q.nodes {
		ids = append(ids, q.nodes[i].ID)
	}

	return ids
}

// light is what the light read answers, each pull request last moved at the
// time updated names for its id, or at fixtureUpdated where it names none.
func (q queueFixture) light(t *testing.T, updated map[string]string) string {
	t.Helper()

	//nolint:tagliatelle // GraphQL answers in camelCase and these names are GitHub's
	type lightNode struct {
		ID         string `json:"id"`
		Number     int    `json:"number"`
		Repository any    `json:"repository"`
		UpdatedAt  string `json:"updatedAt"`
		HeadRefOid string `json:"headRefOid"`
	}

	nodes := make([]lightNode, 0, len(q.nodes))

	for i := range q.nodes {
		n := &q.nodes[i]

		at := updated[n.ID]
		if at == "" {
			at = fixtureUpdated
		}

		nodes = append(nodes, lightNode{
			ID: n.ID, Number: n.Number, Repository: n.Repository,
			UpdatedAt: at, HeadRefOid: strings.Repeat("a", fixtureHeadLen),
		})
	}

	return marshal(t, map[string]any{"data": map[string]any{
		"viewer": q.viewer, "search": map[string]any{"nodes": nodes},
	}})
}

// heavy is what a heavy read of the pull requests ids name answers.
func (q queueFixture) heavy(t *testing.T, ids ...string) string {
	t.Helper()

	var nodes []map[string]json.RawMessage

	for i := range q.nodes {
		if slices.Contains(ids, q.nodes[i].ID) {
			nodes = append(nodes, q.nodes[i].fields)
		}
	}

	return marshal(t, map[string]any{"data": map[string]any{"viewer": q.viewer, "nodes": nodes}})
}

// fixtureUpdated is when the light answer says a pull request last moved, and
// fixtureHeadLen how long the head it names is.
const (
	fixtureUpdated = "2026-08-01T00:00:00Z"
	fixtureHeadLen = 40
)

func marshal(t *testing.T, v any) string {
	t.Helper()

	out, err := json.Marshal(v)
	if err != nil {
		t.Fatalf("writing a fixture answer: %v", err)
	}

	return string(out)
}

// queueInteractions are the calls a cold read of the queue makes.
func queueInteractions(t *testing.T) []ghcassette.Interaction {
	t.Helper()

	q := readQueueFixture(t)
	chunks := conversations.Chunks(q.ids())
	out := make([]ghcassette.Interaction, 0, 1+len(chunks))
	out = append(out, ghcassette.Interaction{
		Args: conversations.LightArgs(conversations.DefaultLimit), Stdout: q.light(t, nil),
	})

	for _, part := range chunks {
		out = append(out, ghcassette.Interaction{Args: conversations.HeavyArgs(part), Stdout: q.heavy(t, part...)})
	}

	return out
}

// queueCassette is the queue's calls and nothing else, saved where a replay
// reads them.
func queueCassette(t *testing.T) string {
	t.Helper()

	path := filepath.Join(t.TempDir(), "threads.golden")
	if err := ghcassette.Save(path, &ghcassette.Cassette{Interactions: queueInteractions(t)}); err != nil {
		t.Fatalf("writing the queue cassette: %v", err)
	}

	return path
}

// The queue screen renders only on a terminal, so this drives the built binary
// through a pty: the buckets are drawn, a row expands where it sits, and what
// was read is written to disk on the way out rather than on every keystroke.
func TestThreadsScreen(t *testing.T) {
	t.Parallel()

	s := ghcassette.Replay(t, queueCassette(t))
	home := quietHome(t)

	// Both, because os.UserConfigDir reads XDG_CONFIG_HOME on Linux and ignores
	// it on macOS: setting only HOME leaves the marks under the harness's own
	// config directory there, where nothing looking under home finds them.
	sc := openReview(t, s, t.TempDir(), "HOME="+home, "XDG_CONFIG_HOME="+home+"/.config", "threads")
	sc.await("2 conversations")
	sc.await(conversations.BucketNew)
	sc.await("a.go:12")

	// enter opens the conversation in place and marks it read, and the row stays
	// where it is: recomputing the bucket after a mark used to move it out from
	// under the cursor.
	sc.press("\r")
	sc.await("read ")

	sc.press("q")

	if code := sc.wait(); code != 0 {
		t.Fatalf("the queue exited %d:\n%s", code, sc.text())
	}

	path := marks(t, home)
	if path == "" {
		t.Fatalf("nothing was written, so the read mark did not survive the screen:\n%s", sc.text())
	}

	raw, err := os.ReadFile(path) // #nosec G304 -- a path this test's own HOME holds
	if err != nil {
		t.Fatal(err)
	}

	// One keypress marks one conversation, and what was written is the row the
	// screen said it read rather than whatever happened to be first.
	if got := strings.Count(string(raw), "[[conversation]]"); got != 1 {
		t.Errorf("wrote %d marks for one keypress:\n%s", got, raw)
	}

	read := readLine.FindStringSubmatch(sc.text())
	if read == nil {
		t.Fatalf("the screen never said what it read:\n%s", sc.text())
	}

	for _, want := range strings.Fields(read[1]) {
		if !strings.Contains(string(raw), want) {
			t.Errorf("it read %q and wrote:\n%s", read[1], raw)
		}
	}
}

// readLine is what the footer says after a conversation is read: the pull
// request and the anchor, which is what the mark on disk has to name.
var readLine = regexp.MustCompile(`read (\S+#\d+ \S+)`)

// The notification stream rides in the same tab as the conversations: the
// fixture's invented repositories stand in for a real stream, which would
// carry private names into a public repository. Space on the first
// notification marks it done, which is the stream's dismissal rather than a
// read mark — nothing is written for it locally.
func TestThreadsScreenNotifications(t *testing.T) {
	t.Parallel()

	body, err := os.ReadFile(filepath.Join("..", "..", "internal", "notice", "testdata", "notifications.json"))
	if err != nil {
		t.Fatalf("reading the notifications fixture: %v", err)
	}

	c := &ghcassette.Cassette{Interactions: append(queueInteractions(t),
		ghcassette.Interaction{Args: notice.Args(), Stdout: string(body)},
		ghcassette.Interaction{Args: []string{"api", "-X", "DELETE", "/notifications/threads/1001"}},
	)}

	cassette := filepath.Join(t.TempDir(), "threads.golden")
	if err := ghcassette.Save(cassette, c); err != nil {
		t.Fatalf("writing the cassette: %v", err)
	}

	s := ghcassette.Replay(t, cassette)
	home := quietHome(t)

	sc := openReview(t, s, t.TempDir(), "HOME="+home, "XDG_CONFIG_HOME="+home+"/.config", "threads")
	sc.await("acme/widgets#42")
	sc.await("shave the yak")

	sc.press(" ")
	sc.await("done acme/widgets#42")

	sc.press("q")

	if code := sc.wait(); code != 0 {
		t.Fatalf("the queue exited %d:\n%s", code, sc.text())
	}

	s.RequireAllPlayed(t)
}

// The status cell says only what the row's words do not: work already staged
// on the pull request, how long the thread has run, and a moved line, with the
// long form spelling out what the short one cuts.
func TestAConversationsStatusSaysWhatIsNotable(t *testing.T) {
	t.Parallel()

	two := []conversations.Note{{Author: "a"}, {Author: "b"}}

	for _, tc := range []struct {
		name        string
		c           conversations.Conversation
		k           inbox.Known
		short, long string
	}{
		{name: "nothing notable", c: conversations.Conversation{Notes: two[:1]}},
		{name: "a reply", c: conversations.Conversation{Notes: two}, short: "2 replies", long: "2 replies"},
		{
			name: "outdated", c: conversations.Conversation{Notes: two[:1], Outdated: true},
			short: "old", long: "outdated",
		},
		{
			name: "work staged", c: conversations.Conversation{Notes: two},
			k:     inbox.Known{Reviewed: true, Draft: 2},
			short: "● 2 drafts · 2 replies", long: "● 2 drafts · 2 replies",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			short, long := main.StatusWordsOf(&tc.c, tc.k)
			if short != tc.short || long != tc.long {
				t.Errorf("the status says %q/%q, want %q/%q", short, long, tc.short, tc.long)
			}
		})
	}
}
