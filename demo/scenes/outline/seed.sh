gen_file() {
  {
    printf 'diff --git a/%s b/%s\nnew file mode 100644\nindex 0000000..3333333\n--- /dev/null\n+++ b/%s\n' "$1" "$1" "$1"
    printf '@@ -0,0 +1,40 @@\n'
    k=1
    while [ "$k" -le 40 ]; do
      printf '+// Code generated by openapi; field %d of model %d.\n' "$k" "$2"
      k=$((k + 1))
    done
  } >>"$patch"
}

