# go_file path n: one hunk adding a checked call inside a function only this
# file names, so nothing gathers it by symbol and it reads under its directory.
go_file() {
  cat >>"$patch" <<HUNK
diff --git a/$1 b/$1
index 1111111..2222222 100644
--- a/$1
+++ b/$1
@@ -10,3 +10,6 @@ func step$2(ctx context.Context) error {
 	ctx = trace(ctx)
+	if err := check(ctx, "$2"); err != nil {
+		return fmt.Errorf("step $2: %w", err)
+	}
 	return nil
HUNK
}

